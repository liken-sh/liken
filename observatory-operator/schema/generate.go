// generate writes every output of the schema, by its path from the
// component's directory, root: the CRD of each template in dir, and
// the Go types of each fields file in dir. The standard sets come from
// indi/standard/ and the simulator transcripts from indi/inditest/testdata/.
func generate(root string) (map[string][]byte, error) {
	dir := filepath.Join(root, "schema")
	sets, _, err := standard.Load(filepath.Join(root, "indi", "standard"), filepath.Join(root, "indi", "inditest", "testdata"))
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	shared := newDeclarations(nil)
	var kinds []kind
	templates, err := filepath.Glob(filepath.Join(dir, "*"+templateSuffix))
	if err != nil {
		return nil, err
	}
	for _, path := range templates {
		plural := strings.TrimSuffix(filepath.Base(path), templateSuffix)
		fieldsPath := filepath.Join(dir, plural+fieldsSuffix)
		_, missing := os.Stat(fieldsPath)
		hasFields := missing == nil
		var settings, status []field
		if hasFields {
			k, err := readKind(fieldsPath, sets)
			if err != nil {
				return nil, err
			}
			kinds = append(kinds, k)
			for _, p := range k.Fields {
				if p.Role == roleSetting {
					settings = append(settings, k.specField(p))
				}
				status = append(status, k.statusField(p))
			}
			hand, err := handWritten(dir, plural)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", path, err)
			}
			if err := collisions(k.Kind, hand, map[string][]field{"spec": settings, "status": status}); err != nil {
				return nil, err
			}
			source, err := k.kindGo(settings, status, shared)
			if err != nil {
				return nil, err
			}
			out[filepath.Join("observatory", "generated_"+strings.ToLower(k.Kind)+".go")] = source
		}
		crd, err := renderCRD(dir, plural, fieldsYAML(settings), fieldsYAML(status))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		var parsed map[string]any
		if err := yaml.UnmarshalStrict([]byte(crd), &parsed); err != nil {
			return nil, fmt.Errorf("the CRD of %s: %w", plural, err)
		}
		text, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		fits := bytes.Contains(text, []byte(`include "fits keywords"`))
		out[filepath.Join("deploy", plural+"-crd.yaml")] = []byte(crdHeader(plural, hasFields, fits) + crd)
	}
	var elements bytes.Buffer
	shared.write(&elements)
	if out[filepath.Join("observatory", "generated_elements.go")], err = goFile(elements.Bytes()); err != nil {
		return nil, err
	}
	if out[filepath.Join("observatory", "generated_standard.go")], err = standardGo(kinds); err != nil {
		return nil, err
	}
	return out, nil
}

// loadKinds reads the standard sets and every fields file in schema/,
// and answers the disagreements that Load found.
func loadKinds(root string) (map[string]standard.Interface, []string, []kind, error) {
	sets, report, err := standard.Load(filepath.Join(root, "indi", "standard"), filepath.Join(root, "indi", "inditest", "testdata"))
	if err != nil {
		return nil, nil, nil, err
	}
	files, err := filepath.Glob(filepath.Join(root, "schema", "*"+fieldsSuffix))
	if err != nil {
		return nil, nil, nil, err
	}
	var kinds []kind
	for _, path := range files {
		k, err := readKind(path, sets)
		if err != nil {
			return nil, nil, nil, err
		}
		kinds = append(kinds, k)
	}
	return sets, report, kinds, nil
}

// crdHeader names the sources of a generated CRD: fitsTemplate only
// for a kind that declares FITS keywords.
func crdHeader(plural string, hasFields, fits bool) string {
	sources := []string{plural + templateSuffix}
	if hasFields {
		sources = append(sources, plural+fieldsSuffix)
	}
	sources = append(sources, deviceTemplate, procedureSchema)
	if fits {
		sources = append(sources, fitsTemplate, "observatory/fitskeywords.go")
	}
	if hasFields {
		sources = append(sources, "indi/standard/")
	}
	last := len(sources) - 1
	listed := strings.Join(sources[:last], ", ") + ", and " + sources[last]
	var b strings.Builder
	for _, line := range wrap("Code generated by TestTheSchemaIsCurrent -update in schema/ from "+listed+"; DO NOT EDIT.", 2) {
		b.WriteString("# " + line + "\n")
	}
	return b.String() + "#\n"
}

// standardGo writes the table of each kind's interfaces: the captures
// of its interfaces, the properties that show that a device serves
// them, and the standard properties that its typed fields hold. A
// numbered family appears as a pattern, such as DIGITAL_OUTPUT_*, and
// a named family as the property whose members name it.
func standardGo(kinds []kind) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Standard is the standard set of a device kind: the INDI interfaces
// that the kind is, by the names of their captures in indi/standard/,
// the properties that show that a device serves them, and the standard
// properties that the kind's typed fields hold. Every other property
// of a device is in status.properties.
type Standard struct {
	Interfaces []string
	// Detect lists the properties that show that a device serves the
	// kind's interfaces. A device that defines one of them serves the
	// kind.
	Detect []string
	// Properties lists the standard properties by name. A property
	// that a driver defines once for each output is a pattern, such as
	// DIGITAL_OUTPUT_*.
	Properties []string
	// NamedBy lists the properties whose members each name a standard
	// property, such as WEATHER_PARAMETERS, whose WEATHER_TEMPERATURE
	// names the property of that parameter's limits.
	NamedBy []string
	// Settings answers a new value of the kind's settings, such as a
	// *CameraSettings, which a spec decodes into. It is nil for a kind
	// with no settings. Each field's indi tag names the property that
	// the operator writes the field to.
	Settings func() any
	// Status answers a new value of the kind's typed status fields,
	// such as a *CameraStandard, which the status writer fills. Each
	// field's indi tag names the property that the field holds.
	Status func() any
}

// Standards holds the standard set of each device kind that has one.
var Standards = map[Kind]Standard{
`)
	for _, k := range kinds {
		var names, namedBy []string
		for _, p := range k.Fields {
			switch p.Family {
			case familyNumbered:
				names = append(names, strings.TrimRight(p.Name, "0123456789")+"*")
			case familyNamed:
				namedBy = append(namedBy, p.NamedBy)
			default:
				names = append(names, p.Name)
			}
		}
		fmt.Fprintf(&b, "\t%sKind: {\n\t\tInterfaces: %s,\n\t\tDetect: %s,\n\t\tProperties: %s,\n", k.Kind,
			goStrings(k.Interfaces), goStrings(k.Detect), goStrings(names))
		if len(namedBy) > 0 {
			fmt.Fprintf(&b, "\t\tNamedBy: %s,\n", goStrings(namedBy))
		}
		if slices.ContainsFunc(k.Fields, func(p property) bool { return p.Role == roleSetting }) {
			fmt.Fprintf(&b, "\t\tSettings: func() any { return new(%sSettings) },\n", k.Kind)
		}
		fmt.Fprintf(&b, "\t\tStatus: func() any { return new(%sStandard) },\n", k.Kind)
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return goFile(b.Bytes())
}

func goStrings(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}
