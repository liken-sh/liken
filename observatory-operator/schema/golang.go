package schema

import (
	"bytes"
	"fmt"
	"go/format"
	"reflect"
	"strings"
)

// goHeader opens every generated Go file.
const goHeader = "// Code generated by TestTheSchemaIsCurrent -update in schema/; DO NOT EDIT.\n\npackage observatory\n\n"

// declarations collects the Go types that the fields of one file use,
// each once, in the order of first use. A shared type goes to shared,
// which the file of the elements declares once for every kind.
type declarations struct {
	order  []*shape
	byName map[string]*shape
	shared *declarations
}

func newDeclarations(shared *declarations) *declarations {
	return &declarations{byName: map[string]*shape{}, shared: shared}
}

// add declares an object and the objects inside it. Two objects of one
// name must be the same, or the generator fails, because Go would hold
// one of them only.
func (d *declarations) add(s *shape) error {
	switch s.Kind {
	case listShape:
		return d.add(s.Item)
	case objectShape:
	default:
		return nil
	}
	target := d
	if s.Shared && d.shared != nil {
		target = d.shared
	}
	if held, seen := target.byName[s.Name]; seen {
		if !reflect.DeepEqual(goShape(held), goShape(s)) {
			return fmt.Errorf("two types are named %s", s.Name)
		}
		return nil
	}
	target.byName[s.Name] = s
	target.order = append(target.order, s)
	for _, f := range s.Fields {
		if err := d.add(f.Type); err != nil {
			return err
		}
	}
	return nil
}

// goShape answers what Go sees of an object: the names and the types
// of its fields, without the descriptions, which differ by use.
func goShape(s *shape) []string {
	var out []string
	for _, f := range s.Fields {
		out = append(out, f.Go+" "+goType(f))
	}
	return out
}

// write writes the declarations as Go source.
func (d *declarations) write(b *bytes.Buffer) {
	for _, s := range d.order {
		writeStruct(b, s.Name, s.Doc, s.Fields)
	}
}

func writeStruct(b *bytes.Buffer, name, doc string, fields []field) {
	for _, line := range wrap(doc, 3) {
		b.WriteString("// " + line + "\n")
	}
	fmt.Fprintf(b, "type %s struct {\n", name)
	for _, f := range fields {
		tag := f.JSON
		if !f.Required {
			tag += ",omitempty"
		}
		indiTag := ""
		if f.INDI != "" {
			indiTag = fmt.Sprintf(" indi:%q", f.INDI)
		}
		fmt.Fprintf(b, "\t%s %s `json:%q%s`\n", f.Go, goType(f), tag, indiTag)
	}
	b.WriteString("}\n\n")
}

// goType answers the Go type of a field. An optional number or object
// is a pointer, so an absent value differs from a zero.
func goType(f field) string {
	return typeOf(f.Type, !f.Required)
}

func typeOf(s *shape, optional bool) string {
	pointer := ""
	if optional {
		pointer = "*"
	}
	switch s.Kind {
	case numberShape:
		return pointer + "float64"
	case int32Shape:
		return "int32"
	case boolShape:
		return "bool"
	case stateShape:
		return "indi.State"
	case listShape:
		return "[]" + typeOf(s.Item, false)
	case objectShape:
		return pointer + s.Name
	}
	return "string"
}

// goFile formats a generated file, and imports indi when a type uses
// its State.
func goFile(body []byte) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(goHeader)
	if bytes.Contains(body, []byte("indi.State")) {
		out.WriteString("import \"github.com/liken-sh/liken/observatory-operator/indi\"\n\n")
	}
	out.Write(body)
	return format.Source(out.Bytes())
}

// kindGo writes the Go types of one kind: <Kind>Settings, which the
// kind's spec embeds, <Kind>Standard, which its status embeds, and
// the type of each field.
func (k kind) kindGo(settings, status []field, shared *declarations) ([]byte, error) {
	var body bytes.Buffer
	decl := newDeclarations(shared)
	if len(settings) > 0 {
		writeStruct(&body, k.Kind+"Settings", k.Kind+"Settings are the settings of a "+k.Kind+
			" that a person states in spec: the standard properties that the operator writes when a reservation configures the device.", settings)
	}
	interfaces := strings.ToUpper(strings.Join(k.Interfaces, " and ")) + " interface"
	if len(k.Interfaces) > 1 {
		interfaces += "s"
	}
	writeStruct(&body, k.Kind+"Standard", k.Kind+"Standard holds each standard property of INDI's "+
		interfaces+" in status, as the driver reports it.", status)
	for _, f := range append(append([]field{}, settings...), status...) {
		if err := decl.add(f.Type); err != nil {
			return nil, fmt.Errorf("%s: %w", k.Kind, err)
		}
	}
	decl.write(&body)
	return goFile(body.Bytes())
}
